#!/usr/bin/env python3
"""Generate the standalone Challenge from the maintained Mathlib-only statement."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THEOREM = """
universe u v' u'

/-- **Theorem A** (Theorem 4.5). Over every field there is an essentially small linear
extriangulated category with no triangulated embedding, whose countable families of objects lie in
extension-closed subcategories with algebraic realizations, and which is hereditary,
Krull–Schmidt, with enough injectives and `ℵ₁` indecomposables. -/
theorem ExtriangulatedRealization.Challenge.theoremA : ExtriangulatedRealization.Statement.TheoremA.{u, v', u'} := by
  sorry

/-- **Theorem B** (Theorem 3.1). `C(D)` admits a triangulated embedding if and only if every
projection `lim D → D_i` is surjective, if and only if `C(D)` has an algebraic realization. -/
theorem ExtriangulatedRealization.Challenge.theoremB : ExtriangulatedRealization.Statement.TheoremB.{u} := by
  sorry

/-- **Theorem B**, (1) ⇒ (2), for triangulated targets in all universes. -/
theorem ExtriangulatedRealization.Challenge.theoremB_necessity : ExtriangulatedRealization.Statement.TheoremB_necessity.{u, v', u'} := by
  sorry

/-- **Proposition 2.3.** Compatible surjections from one vector space give an algebraic
realization of `C_J`. -/
theorem ExtriangulatedRealization.Challenge.proposition_2_3 : ExtriangulatedRealization.Statement.Proposition_2_3.{u} := by
  sorry

/-- **Corollary 2.4.** `C(D)` is an essentially small extriangulated category; each `C_J` is
extension-closed; `C_J` is algebraically realized when `J` has a largest element. -/
theorem ExtriangulatedRealization.Challenge.corollary_2_4 : ExtriangulatedRealization.Statement.Corollary_2_4.{u} := by
  sorry

/-- **Proposition 4.4.** Krull–Schmidt, indecomposables, extension spaces, enough injectives
and heredity of `C(D)`. -/
theorem ExtriangulatedRealization.Challenge.proposition_4_4 : ExtriangulatedRealization.Statement.Proposition_4_4.{u} := by
  sorry

/-- **Proposition 4.6** (1), (2). Countable cofinality or finite-dimensional terms give an
algebraic realization. -/
theorem ExtriangulatedRealization.Challenge.proposition_4_6 : ExtriangulatedRealization.Statement.Proposition_4_6.{u} := by
  sorry
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if Challenge.lean is stale")
    args = parser.parse_args()
    source = (ROOT / "ExtriangulatedRealization/Statement.lean").read_text()
    imports = [line.split()[-1] for line in source.splitlines()
               if line.startswith(("import ", "public import "))]
    if not imports or any(name != "Mathlib" and not name.startswith("Mathlib.") for name in imports):
        raise SystemExit("Statement.lean must import only Mathlib")
    expected = "-- Generated by scripts/generate_challenge.py; edit Statement.lean.\n" + source + THEOREM
    target = ROOT / "Challenge.lean"
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit("Challenge.lean is stale; run scripts/generate_challenge.py")
    else:
        target.write_text(expected)
    print(f"Challenge.lean: {len(expected.splitlines())} lines, {len(expected.encode())} bytes")


if __name__ == "__main__":
    main()
